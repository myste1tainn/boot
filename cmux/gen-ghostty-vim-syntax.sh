#!/usr/bin/env bash
# Generate PLAIN VIM filetype support for the Ghostty-format cmux config
# (~/.config/ghostty/config), into this repo's cmux/files/.vim/ tree.
#
# Neovim does not need this: it uses the real tree-sitter-ghostty grammar
# (parser + highlight queries), wired up in the nvim config repo as a plugin.
# Plain vim cannot load a tree-sitter grammar, so it gets a vim syntax file —
# which is also what Ghostty upstream ships for vim. Upstream generates those
# files at build time from its compiled option list rather than publishing them,
# so this does the same, reading the option list from the ghostty binary that
# cmux bundles. The recognised keys then match the installed version exactly.
#
# Re-run after a cmux upgrade, then commit the result.
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname "$0")" >/dev/null 2>&1; pwd -P)"
VIM_DIR="${VIM_DIR:-$SCRIPT_DIR/files/.vim}"
GHOSTTY="${GHOSTTY:-/Applications/cmux.app/Contents/Resources/bin/ghostty}"

if [[ ! -x "$GHOSTTY" ]]; then
  echo "ghostty binary not found at $GHOSTTY" >&2
  echo "set GHOSTTY=/path/to/ghostty, or install cmux" >&2
  exit 1
fi

VERSION="$("$GHOSTTY" +version 2>/dev/null \
  | sed -n 's/^[[:space:]]*-[[:space:]]*version:[[:space:]]*//p' | head -1)"
VERSION="${VERSION:-unknown}"

# Config option names, and keybind action names, straight from the binary.
# Read with a plain loop rather than mapfile: this repo bootstraps fresh macOS
# machines, where /bin/bash is still 3.2 and has no mapfile.
KEYS=() ACTIONS=()
while IFS= read -r LINE; do KEYS+=("$LINE"); done < <(
  "$GHOSTTY" +show-config --default 2>/dev/null \
    | sed -n 's/^\([a-z0-9][a-z0-9-]*\) *=.*/\1/p' | sort -u)
while IFS= read -r LINE; do ACTIONS+=("$LINE"); done < <(
  "$GHOSTTY" +list-actions 2>/dev/null \
    | sed -n 's/^\([a-z0-9][a-z0-9_]*\).*/\1/p' | sort -u)

if ((${#KEYS[@]} == 0)); then
  echo "could not read any config keys from $GHOSTTY" >&2
  exit 1
fi

STAMP="generated by cmux/gen-ghostty-vim-syntax.sh from ghostty $VERSION"

mkdir -p "$VIM_DIR/ftdetect" "$VIM_DIR/syntax" "$VIM_DIR/ftplugin"

# ── ftdetect ────────────────────────────────────────────────────────────────
# Same paths Ghostty's own ftdetect claims, which is where cmux reads from too.
cat > "$VIM_DIR/ftdetect/ghostty.vim" <<VIMFILE
" Ghostty / cmux terminal config files.
" $STAMP
autocmd BufRead,BufNewFile */ghostty/config    setfiletype ghostty
autocmd BufRead,BufNewFile */ghostty/themes/*  setfiletype ghostty
VIMFILE

# ── ftplugin ────────────────────────────────────────────────────────────────
cat > "$VIM_DIR/ftplugin/ghostty.vim" <<VIMFILE
" $STAMP
setlocal commentstring=#\ %s
setlocal comments=:#
" Keys are kebab-case, so keep them one word for w/e/iw and completion.
setlocal iskeyword+=-
VIMFILE

# ── syntax ──────────────────────────────────────────────────────────────────
{
  echo "\" Vim syntax file for Ghostty / cmux config files."
  echo "\" $STAMP"
  echo "\" Do not edit by hand — re-run the generator instead."
  echo
  echo 'if exists("b:current_syntax")'
  echo '  finish'
  echo 'endif'
  echo
  echo '" Comments'
  echo 'syn match ghosttyComment "^\s*#.*$" contains=@Spell'
  echo
  echo '" Values, matched inside a key=value line'
  echo 'syn match ghosttyEquals "=" contained'
  echo 'syn match ghosttyColor "#[0-9a-fA-F]\{6\}\>" contained'
  echo 'syn match ghosttyColor "#[0-9a-fA-F]\{3\}\>" contained'
  echo 'syn match ghosttyNumber "\<\d\+\%(\.\d\+\)\?\>" contained'
  echo 'syn keyword ghosttyBoolean true false contained'
  echo
  echo '" Keybind action names (ghostty +list-actions)'
  printf 'syn keyword ghosttyAction contained'
  for a in "${ACTIONS[@]}"; do printf ' %s' "$a"; done
  printf '\n'
  echo
  echo '" Recognised option names (ghostty +show-config --default).'
  echo '" An unrecognised key simply stays unhighlighted — it is not flagged as an'
  echo '" error, because cmux may accept keys this ghostty build does not list.'
  printf 'syn keyword ghosttyKey contained'
  for k in "${KEYS[@]}"; do printf ' %s' "$k"; done
  printf '\n'
  echo
  echo '" A whole setting line: key, then everything after the = as the value.'
  echo 'syn region ghosttyValue start="=" end="$" contained keepend'
  echo '      \ contains=ghosttyEquals,ghosttyColor,ghosttyNumber,ghosttyBoolean,ghosttyAction'
  echo 'syn match ghosttyLine "^\s*[a-zA-Z0-9-]\+\s*=.*$"'
  echo '      \ contains=ghosttyKey,ghosttyValue'
  echo
  echo 'hi def link ghosttyComment Comment'
  echo 'hi def link ghosttyKey     Keyword'
  echo 'hi def link ghosttyEquals  Operator'
  echo 'hi def link ghosttyColor   Constant'
  echo 'hi def link ghosttyNumber  Number'
  echo 'hi def link ghosttyBoolean Boolean'
  echo 'hi def link ghosttyAction  Function'
  echo
  echo 'let b:current_syntax = "ghostty"'
} > "$VIM_DIR/syntax/ghostty.vim"

echo "ghostty $VERSION: ${#KEYS[@]} config keys, ${#ACTIONS[@]} actions"
echo "wrote:"
echo "  $VIM_DIR/ftdetect/ghostty.vim"
echo "  $VIM_DIR/ftplugin/ghostty.vim"
echo "  $VIM_DIR/syntax/ghostty.vim"
